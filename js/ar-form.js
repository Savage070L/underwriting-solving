// ar-form.js — ДАННЫЕ и ПРАВИЛА формы «АРешение» (Рекомендация ДАиП →
// Заключение по управлению рисками → Андеррайтинговое решение).
//
// САМ ДОКУМЕНТ СТРОИТ js/ar-form-pdf.js — форма печатается только в PDF: в неё
// вшиты факсимиле подписантов, а подписанный документ не должен быть
// редактируемым. Прежний .docx-построитель убран отсюда (история в git).
//
// Здесь остаётся то, что нужно и разметке, и таблице-превью: форматтеры
// (_money/_pct/_int/_dateRu…), выбор наименования (_effName), текст решения,
// геометрия бланка (COLS) и подписанты с факсимиле.
//
// Источник данных — строка из BatchReader.parse(); официальное название/адрес
// берутся из statgov, если есть. № документа = номер договора.

const ARForm = {
  MONTHS_GEN: [
    'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
    'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
  ],

  // Подписанты по умолчанию. Эффективные значения берутся из «Справочников»
  // (App._getSigner) — эти константы работают как запасные, когда справочник
  // недоступен (например, при запуске генератора вне приложения).
  // С 01.07.2026 Рекомендацию ДАиП подписывает Джелкобаев, а не Бурханов.
  UNDERWRITER: 'Джелкобаев Т.К.',
  RISK_MANAGER: 'Осинцев Р.С.',

  // ===== ФАКСИМИЛЕ (подписи) =====
  // Картинки лежат в репозитории и встраиваются в КАЖДЫЙ документ, поэтому
  // обрезаны по содержимому и сжаты до 300 px (5–7 КБ): при печати пакета из
  // сотен договоров вес важнее избыточного разрешения.
  //
  // ВАЖНО: факсимиле привязано к ФАМИЛИИ, а не к должности. Если в справочнике
  // поставят другого подписанта, его строка напечатается со старым пустым
  // прочерком — чужую подпись не подставляем ни при каких условиях.
  // Отчество Джелкобаева пользователь не знал точно — «Талгат К.», записано в
  // принятом формате «Фамилия И.О.». Если инициал окажется другим, правится
  // одним полем в «Справочниках» (Директор ДАиП), код трогать не нужно.
  // dy — ВЕРТИКАЛЬНАЯ ПОСАДКА КОНКРЕТНОЙ ПОДПИСИ на прочерк, в миллиметрах.
  // Она у каждой своя, и это не придирка: картинка обрезана по чернилам, а
  // чернила внутри рамки распределены по-разному — у Осинцева длинный хвост
  // уходит вниз, у Джелкобаева росчерк компактнее. При одинаковом сдвиге одна
  // садится на линию правильно, вторая висит над ней. Значения выверены по
  // файлу, где пользователь сам расставил подписи, и сверены попиксельно.
  // Знак обратный привычному: отступ считается как -(высота + dy), поэтому
  // МЕНЬШЕ значение = НИЖЕ подпись.
  // dx/dy — посадка КОНКРЕТНОЙ подписи относительно прочерка, в миллиметрах
  // (dx — вправо, dy — вверх). Значения у каждой свои, и это не придирка:
  // картинки обрезаны по чернилам, но росчерки разной формы и ШИРЕ прочерка
  // (21 мм), поэтому при простом центрировании левый край наползает на ФИО —
  // у широкой подписи Осинцева сильнее, чем у Джелкобаева. Значения выверены
  // по файлам, где пользователь сам расставил подписи.
  SIGNATURES: [
    { match: 'джелкобаев', file: 'assets/signatures/dzhelkobaev.png', dx: 2, dy: 4.9 },
    { match: 'осинцев', file: 'assets/signatures/osintsev.png', dx: 4, dy: 2.6 },
  ],
  SIG_DX_DEFAULT: 0,     // для подписи, у которой dx не задан
  SIG_DY_DEFAULT: 0.2,   // для подписи, у которой dy не задан
  // Факсимиле — ПЛАВАЮЩАЯ картинка (floating, wrap: NONE).
  // Строка подписи в бланке узкая (≈3,6 мм — одна строка 8 pt), а бланк свёрстан
  // ровно под один лист A4. Строчная (inline) картинка растянула бы строку до
  // ~9 мм — именно это и просили убрать. Плавающая на вёрстку не влияет ВООБЩЕ:
  // строка остаётся прежней высоты, текст «ФИО ______ Подпись» цел (прочерк под
  // живую подпись на месте), а подпись ложится ПОСЛЕ слова «Подпись» — и, как
  // настоящая, слегка заходит на соседние строки.
  // Подпись лежит ПОВЕРХ ПРОЧЕРКА — между ФИО и словом «Подпись», как
  // настоящая роспись на линии (позиция выверена по образцу пользователя).
  // По горизонтали она центрируется ПО САМОМУ ПРОЧЕРКУ (см. ar-form-pdf.js),
  // поэтому не зависит от длины ФИО.
  SIG_HEIGHT: 67,        // px при 96 dpi ≈ 17,7 мм
  EMU_MM: 36000,         // 1 мм = 36 000 EMU
  _sigCache: null,       // {file: {data, width, height}}

  // Запись о факсимиле по ФИО подписанта (или null, если подписи нет).
  _sigFor(name) {
    const n = String(name || '').toLowerCase();
    return ARForm.SIGNATURES.find(s => n.includes(s.match)) || null;
  },
  _sigFileFor(name) {
    const hit = ARForm._sigFor(name);
    return hit ? hit.file : null;
  },

  // Ширина/высота PNG из заголовка IHDR (13-й…20-й байты) — без декодирования.
  async _pngSize(buf) {
    const dv = new DataView(buf instanceof ArrayBuffer ? buf : new Uint8Array(buf).buffer);
    if (dv.byteLength < 24 || dv.getUint32(0) !== 0x89504E47) return null;
    return { width: dv.getUint32(16), height: dv.getUint32(20) };
  },
  // Должность Осинцева Р.С. — как в подписных блоках (AS_MEMBERS в utils.js),
  // а не «Риск-менеджер».
  RISK_MANAGER_ROLE: 'Руководитель Службы управления рисками',
  RISK_TEXT: 'Обязательное страхование работника от несчастного случая при исполнении им трудовых (служебных) обязанностей',
  CLASS_TEXT: 'Страхование от несчастных случаев',

  // Для HTML-таблицы превью (batch-ar.js)
  _esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  },

  // Имя для отображения/документа: по умолчанию из выгрузки (Контрагент = excelName).
  // Если оно длиннее 100 символов (1С такие обрезает) — берём официальное имя из
  // statgov, иначе из kyc, иначе оставляем как есть.
  _effName(row) {
    if (!row) return '';
    const excel = String(row.excelName || row.insurerName || '').trim();
    if (excel.length <= 100) return excel;
    const sg = (row.statgov && !row.statgov.error && row.statgov.name) ? String(row.statgov.name).trim() : '';
    const kyc = (row.kyc && !row.kyc.error && row.kyc.found !== false && row.kyc.name) ? String(row.kyc.name).trim() : '';
    return sg || kyc || excel;
  },

  // «12» июня 2026 г. (пусто → плейсхолдер бланка)
  _dateRu(d) {
    if (!(d instanceof Date) || isNaN(d)) return '«__» __________ 20__ г.';
    return `«${String(d.getDate()).padStart(2, '0')}» ${ARForm.MONTHS_GEN[d.getMonth()]} ${d.getFullYear()} г.`;
  },

  _money(v) {
    if (v == null || isNaN(v)) return '';
    const num = Math.round(Number(v) * 100) / 100;
    const parts = num.toFixed(2).split('.');
    const intPart = parts[0].replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
    return parts[1] === '00' ? intPart : intPart + ',' + parts[1];
  },

  _int(v) {
    if (v == null || isNaN(v)) return '';
    return String(Math.round(v)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  },

  _pct(v) {
    if (v == null || isNaN(v)) return '';
    return (v * 100).toFixed(2).replace('.', ',') + '%';
  },

  // « — резидент» / « — нерезидент» к БИН в документе. Источник — локальный
  // индекс ГБД ЮЛ (js/resident-check.js). Если индекс не загружен или это ИИН
  // (реестр юр. лиц неприменим) — суффикс пустой, форма остаётся как была.
  _residencySuffix(bin) {
    if (typeof ResidentCheck === 'undefined' || !ResidentCheck.ready()) return '';
    const res = ResidentCheck.check(bin);
    if (res.status === 'resident') return ' — резидент';
    if (res.status === 'nonresident') return ' — нерезидент';
    return '';
  },

  _coeff(v) {
    if (v == null || isNaN(v)) return '1';
    return String(v).replace('.', ',');
  },

  decisionText(row) {
    return row.decision === 'discount'
      ? `принятие с понижающим коэффициентом (${ARForm._coeff(row.coeff)})`
      : 'принятие со стандартным тарифом';
  },

  // ===== Геометрия таблицы =====
  // A4 книжная: ширина 11906 twips. Поля 1 см (567) по бокам → usable ≈ 10772.
  // 9 колонок: метка + 8 данных. Итог = 10466 twips (помещается).
  COLS: [1700, 1096, 1096, 1096, 1096, 1096, 1096, 1096, 1094],
  get TOTAL() { return ARForm.COLS.reduce((a, b) => a + b, 0); },
  get DATA_W() { return ARForm.COLS.slice(1).reduce((a, b) => a + b, 0); }, // 8 колонок данных

  // Кегли и шрифт живут в ar-form-pdf.js (там они в пунктах, а не в
  // полупунктах .docx). Здесь остаётся только геометрия колонок — она в твипах
  // и общая: PDF пересчитывает её в пункты.

};

if (typeof window !== 'undefined') window.ARForm = ARForm;
if (typeof module !== 'undefined' && module.exports) module.exports = ARForm;
